function untie(out, floor, correct) {
  for (let guard = 0; guard < out.length * 12; guard++) {
    const seen = new Map();
    let dup = -1;
    for (let i = 0; i < out.length; i++) {
      if (seen.has(out[i])) { dup = i; break; }
      seen.set(out[i], i);
    }
    if (dup < 0) return out;
    let donor = -1;
    for (let i = 0; i < out.length; i++) {
      if (i === dup || i === correct || out[i] <= floor) continue;
      if (donor < 0 || out[i] > out[donor]) donor = i;
    }
    if (donor < 0 && correct !== dup && out[correct] > floor) donor = correct;
    if (donor < 0) break;
    const taken = new Set(out.filter((_, i) => i !== dup));
    let next = out[dup] + 1;
    while (taken.has(next)) next += 1;
    const moved = Math.min(next - out[dup], out[donor] - floor);
    if (moved <= 0) break;
    out[donor] -= moved;
    out[dup] += moved;
  }
  return out;
}

/** The judged split, or null when this question was not one of those read. */
export function judgedPercents(questionId, n, correctIndex) {
  const row = JUDGED.get(Number(questionId));
  if (!row || n !== 5 || row.correct !== correctIndex) return null;
  const { band, correct, traps } = row;
  const h = hashId(questionId);
  const floor = 5;
  const out = Array(n).fill(floor);
  let spare = 100 - floor * n;
  const trapAbove = band === 0 ? 5 + (h % 3)
    : band === 1 ? 12 + (h % 4)
    : band === 2 ? 16 + (h % 4)
    : 22 + (h % 3);
  const secondAbove = band === 3 ? 4 + (h % 2) : band >= 2 ? 6 + (h % 3) : 0;
  const give = (idx, amount) => {
    const moved = Math.max(0, Math.min(amount, spare));
    out[idx] += moved;
    spare -= moved;
  };
  if (traps[0] !== undefined) give(traps[0], trapAbove);
  if (secondAbove && traps[1] !== undefined) give(traps[1], secondAbove);
  out[correct] += spare;
  let bonus = 3;
  const rest = traps.slice(secondAbove ? 2 : 1);
  for (const idx of rest) {
    if (bonus <= 0) break;
    const top = traps[0];
    const keyFloor = band === 3 ? 50 : band === 2 ? 54 : 0;
    if (keyFloor && out[correct] - Math.min(bonus, 2) < keyFloor) break;
    if (out[correct] - out[top] <= 10) break;
    const moved = Math.min(bonus, 2, out[correct] - floor);
    out[idx] += moved;
    out[correct] -= moved;
    bonus -= moved;
  }
  if (out[correct] - out[traps[0]] < 8) {
    const need = 8 - (out[correct] - out[traps[0]]);
    const room = out[traps[0]] - floor;
    const moved = Math.min(need, room);
    out[traps[0]] -= moved;
    out[correct] += moved;
  }
  return untie(out, floor, correct);
}

